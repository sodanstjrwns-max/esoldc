export function areaTreatmentLinks(area: Pick<NearbyArea, 'slug' | 'name'>): { name: string; path: string; slug: string }[] {
  if (area.slug === 'maseok') return MASEOK_LOCAL.map(m => ({ name: m.name, path: `/area/maseok-${m.slug}`, slug: m.slug }));
  return CORE_TREATMENTS.map(t => ({ name: `${area.name} ${t.name}`, path: `/area/${area.slug}-${t.slug}`, slug: t.slug }));
}
